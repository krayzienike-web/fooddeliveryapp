const TAGS = ['Горячее', 'Вкусно', 'Большая порция', 'Красиво', 'Быстро', 'Как на фото'];
const MIXED = ['Вкусно, но хотелось бы чуть горячее.', 'Хорошо, но курьер немного задержался.', 'Нормально, в прошлый раз было лучше.'];

function rnd(seed: number) {
  let s = seed;
  return () => {
    s = (s * 1664525 + 1013904223) % 4294967296;
    return s / 4294967296;
  };
}

export function reviewsForDish(dish: Dish, now: number): Review[] {
  const r = rnd(dish.id.split('').reduce((a, ch) => a + ch.charCodeAt(0), 0));
  const pool = POSITIVE[dish.categoryId] ?? POSITIVE.combo;
  return Array.from({ length: 5 }, (_, i) => {
    const mixed = r() < 0.15;
    const stars = mixed ? 4 : r() < 0.8 ? 5 : 4;
    return {
      id: `rv-${dish.id}-${i}`,
      dishId: dish.id,
      author: REVIEW_AUTHORS[Math.floor(r() * REVIEW_AUTHORS.length)],
      stars,
      text: mixed ? MIXED[Math.floor(r() * MIXED.length)] : pool[i % pool.length],
      tags: [TAGS[Math.floor(r() * TAGS.length)], TAGS[Math.floor(r() * TAGS.length)]].filter((v, k, a) => a.indexOf(v) === k),
      photo: i === 0 ? dish.image : undefined,
      createdAt: now - Math.floor(r() * 30 + i * 3) * 86400000,
      helpful: Math.floor(r() * 40),
    };
  });
}
