"""Download picked Pexels photos, crop to 4:5 / 1:1, export WebP, and generate src/shared/assets/media.ts."""
import json, sys, urllib.request, concurrent.futures as cf, io
from pathlib import Path
from PIL import Image, ImageOps
ROOT = Path(__file__).resolve().parents[2]
CACHE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / '.photo-cache'
OUT = ROOT / 'assets' / 'img'
picks = json.loads((Path(__file__).parent / 'picks.json').read_text())
CACHE.mkdir(parents=True, exist_ok=True); OUT.mkdir(parents=True, exist_ok=True)

def fetch(item):
    key, pid = item
    raw = CACHE / f'{pid}.jpg'
    if not raw.exists():
        url = f'https://images.pexels.com/photos/{pid}/pexels-photo-{pid}.jpeg?auto=compress&cs=tinysrgb&w=1200'
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        raw.write_bytes(urllib.request.urlopen(req, timeout=60).read())
    im = Image.open(raw).convert('RGB')
    wide = key.startswith(('rest-', 'kitchen-', 'banquet-'))
    tall = key.startswith('reel-')
    if tall:
        im = ImageOps.fit(im, (720, 1280), centering=(0.5, 0.5))
        im.save(OUT / f'{key}.webp', 'WEBP', quality=70, method=6)
    elif wide:
        im = ImageOps.fit(im, (1080, 720), centering=(0.5, 0.5))
        im.save(OUT / f'{key}.webp', 'WEBP', quality=68, method=6)
    else:
        big = ImageOps.fit(im, (800, 800), centering=(0.5, 0.5))
        big.save(OUT / f'{key}.webp', 'WEBP', quality=72, method=6)
        big.resize((320, 320), Image.LANCZOS).save(OUT / f'{key}@s.webp', 'WEBP', quality=68, method=6)
    tiny = im.resize((1, 1), Image.BOX).getpixel((0, 0))
    return key, '#%02x%02x%02x' % tiny

with cf.ThreadPoolExecutor(10) as ex:
    res = dict(ex.map(fetch, picks.items()))

lines = ['// Generated by scripts/photos/build.py — do not edit by hand.', '/* eslint-disable */', '',
         'export interface MediaEntry { full: number; small?: number; tint: string }', '',
         'export const MEDIA: Record<string, MediaEntry> = {']
for key in picks:
    small = '' if key.startswith(('rest-', 'kitchen-', 'banquet-', 'reel-')) else f", small: require('../../../assets/img/{key}@s.webp')"
    lines.append(f"  '{key}': {{ full: require('../../../assets/img/{key}.webp'){small}, tint: '{res[key]}' }},")
lines += ['};', '', "/** Photo credits: all images from Pexels (pexels.com/license), ids in scripts/photos/picks.json. */", '']
dst = ROOT / 'src' / 'shared' / 'assets'; dst.mkdir(parents=True, exist_ok=True)
(dst / 'media.ts').write_text('\n'.join(lines))
print('ok', len(res))
